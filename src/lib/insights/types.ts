import type { HealthCheckIn } from "../health/validation";
import type { Indicator, MonitoringCategory } from "./config";
export type Evidence = {
  id: string;
  missionDate: string;
  recordedAt: string;
  source: HealthCheckIn["source"];
  indicator: Indicator;
  value: number | string;
  role?: "current" | "baseline" | "pattern";
};
export type IndicatorAnalysis = {
  key: Indicator;
  current: Evidence | null;
  baseline: number | string | null;
  baselineCount: number;
  baselineEvidence: Evidence[];
  baselineFrom: string | null;
  baselineTo: string | null;
  percentageChange: number | null;
  difference: number | null;
  rolling7: number | null;
  rolling30: number | null;
  rolling7Count: number;
  rolling30Count: number;
  variability: number | null;
  slope: number | null;
  trendSamples: number;
  consecutive: { direction: "up" | "down" | "none"; intervals: number };
  repeatedDeviations: number;
  outlierIds: string[];
  category: MonitoringCategory;
  limitations: string[];
};
export type InsightObservation = {
  id: string;
  kind: "indicator" | "combination" | "urgent";
  indicators: Indicator[];
  category: MonitoringCategory;
  title: string;
  explanation: string;
  comparison: string;
  period: string;
  evidence: Evidence[];
  limitations: string[];
  nextStep: string;
  references: string[];
  rule: string;
};
export type AnalysisOptions = {
  profileId: string;
  asOf: string;
  mode?: "demo" | "authenticated";
  minBaseline?: number;
  baselineDays?: number;
  freshnessHours?: number;
};
export type AnalysisReport = {
  profileId: string;
  asOf: string;
  validClock: boolean;
  records: HealthCheckIn[];
  current: HealthCheckIn | null;
  metrics: IndicatorAnalysis[];
  observations: InsightObservation[];
  urgentRecordIds: string[];
  quality: {
    invalid: number;
    future: number;
    otherProfile: number;
    otherSource: number;
    duplicate: number;
    conflicting: number;
    sameDay: number;
    missingDays7: number;
    completeCells7: number;
    expectedCells7: number;
    days7: number;
  };
  submissionAgeHours: number | null;
  missionAgeDays: number | null;
  stale: boolean;
  limitations: string[];
  configuration: {
    minBaseline: number;
    baselineDays: number;
    freshnessHours: number;
  };
};
export type TimelineEntry = {
  missionDate: string;
  asOf: string;
  stable: number;
  change: number;
  review: number;
  titles: string[];
  evidenceIds: string[];
  urgent: boolean;
};
